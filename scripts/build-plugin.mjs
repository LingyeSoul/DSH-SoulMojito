import { build } from 'esbuild'
import { resolve } from 'node:path'

const root = resolve(import.meta.dirname, '..')
await build({
  entryPoints: [resolve(root, 'packages/plugin/src/index.ts')],
  outfile: resolve(root, 'packages/plugin/index.mjs'),
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node22',
  sourcemap: false,
  packages: 'bundle',
  banner: { js: '// Generated by scripts/build-plugin.mjs. Do not edit.\n' },
})
console.log('built packages/plugin/index.mjs')
