function assembleClientSource(root) {
  const sourceDir = resolve(root, 'packages/plugin/client-src')
  const manifestPath = resolve(sourceDir, 'manifest.json')
  const manifest = JSON.parse(readFileSync(manifestPath, 'utf8'))
  const fragments = manifest?.fragments
  if (!Array.isArray(fragments) || fragments.length === 0) {
    throw new Error('client-src/manifest.json must declare a non-empty fragments array')
  }
  const listed = new Set(fragments)
  for (const entry of readdirSync(sourceDir)) {
    if (entry.endsWith('.js') && !listed.has(entry)) {
      throw new Error(`client fragment '${entry}' is not listed in client-src/manifest.json`)
    }
  }
  const body = fragments.map((name) => {
    if (typeof name !== 'string' || name === '' || name.includes('/') || name.includes('\\')) {
      throw new Error(`invalid client fragment name: ${String(name)}`)
    }
    return readFileSync(resolve(sourceDir, name), 'utf8')
  }).join('\n')
  return `// Generated by scripts/build-plugin.mjs from packages/plugin/client-src. Do not edit.\n${body}`
}

function indentCode(code, width) {
  const pad = ' '.repeat(width)
  return code.split('\n').map((line) => (line === '' ? line : pad + line)).join('\n')
}

function resolveCommit() {
  const configured = [
    process.env.DSH_SOULMOJITO_COMMIT,
    process.env.DSH_TAVERN_COMMIT,
    process.env.GITHUB_SHA,
    process.env.CI_COMMIT_SHA,
    process.env.BUILD_SOURCEVERSION,
  ].map(normalizeCommit).find(Boolean)
  if (configured) return configured

  try {
    return normalizeCommit(execFileSync('git', ['rev-parse', '--short=7', 'HEAD'], {
      cwd: root,
      encoding: 'utf8',
      windowsHide: true,
    })) ?? 'unknown'
  } catch {
    return 'unknown'
  }
}

function normalizeCommit(value) {
  const commit = value?.trim()
  return commit && /^[0-9a-f]{7,40}$/i.test(commit)
    ? commit.slice(0, 7).toLowerCase()
    : undefined
}
